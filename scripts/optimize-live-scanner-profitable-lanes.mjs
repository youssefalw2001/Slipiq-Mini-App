#!/usr/bin/env node
/*
  Optimize live-scanner parity rows by profitable lane combinations.

  Input is the artifact generated by backtest-live-scanner-parity-from-warehouse.mjs.
  It uses live_scanner_parity_unique_customer_rows.csv and tests focused scenarios:
  - Core + Reverse
  - Core + Reverse + Research P2
  - Core + Reverse + Research P2 + V3
  - Core + Reverse + limited Mirror variants
  - negative-control Core Cluster Plus
*/

import fs from 'node:fs';
import path from 'node:path';

const args = Object.fromEntries(process.argv.slice(2).map((arg) => arg.match(/^--([^=]+)=(.*)$/)).filter(Boolean).map((m) => [m[1], m[2]]));
const inputDir = args['input-dir'] || 'artifacts/output/live-scanner-parity-backtest';
const outDir = args.out || 'artifacts/output/optimized-profitable-lanes';
const bankroll = Number(args.bankroll || '3000') || 3000;
const riskPcts = String(args['risk-pcts'] || '0.03,0.05,0.07').split(',').map((v) => Number(v.trim())).filter((v) => Number.isFinite(v) && v > 0 && v < 1);
const inputPath = path.join(inputDir, 'live_scanner_parity_unique_customer_rows.csv');

function ensureDir(dir) { fs.mkdirSync(dir, { recursive: true }); }
function clean(v) { return String(v ?? '').replace(/\s+/g, ' ').trim(); }
function num(v) { if (v === undefined || v === null || clean(v) === '') return null; const n = Number(String(v).replace(',', '.')); return Number.isFinite(n) ? n : null; }
function csvEscape(v) { const s = String(v ?? ''); return /[",\n\r]/.test(s) ? `"${s.replaceAll('"', '""')}"` : s; }
function writeCsv(file, rows, fields) { ensureDir(path.dirname(file)); fs.writeFileSync(file, [fields.join(','), ...rows.map((r) => fields.map((f) => csvEscape(r[f])).join(','))].join('\n') + '\n', 'utf8'); }
function writeJson(file, value) { ensureDir(path.dirname(file)); fs.writeFileSync(file, JSON.stringify(value, null, 2), 'utf8'); }

function parseCsv(text) {
  const rows = []; let row = []; let cell = ''; let q = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i], nx = text[i + 1];
    if (q) {
      if (ch === '"' && nx === '"') { cell += '"'; i += 1; }
      else if (ch === '"') q = false;
      else cell += ch;
    } else if (ch === '"') q = true;
    else if (ch === ',') { row.push(cell); cell = ''; }
    else if (ch === '\n') { row.push(cell); rows.push(row); row = []; cell = ''; }
    else if (ch !== '\r') cell += ch;
  }
  if (cell.length || row.length) { row.push(cell); rows.push(row); }
  if (!rows.length) return [];
  const h = rows[0];
  return rows.slice(1).filter((r) => r.some((c) => c !== '')).map((r) => Object.fromEntries(h.map((k, i) => [k, r[i] ?? ''])));
}

function rank(row) {
  const tierRank = ({ S: 4, A: 3, B: 2, Research: 1 })[row.public_tier] || 0;
  return tierRank * 1000000 + Number(row.quality || 0) * 100000 + Number(row.protected_grouped_odds || row.gate_grouped_odds || 0) * 100 + Number(row.trigger_odds || 0);
}
function capMirror(rows, perMonthCap) {
  if (!perMonthCap || perMonthCap <= 0) return [];
  const byMonth = new Map();
  for (const r of rows) { const m = clean(r.event_date).slice(0, 7); if (!byMonth.has(m)) byMonth.set(m, []); byMonth.get(m).push(r); }
  const keep = [];
  for (const [month, arr] of [...byMonth.entries()].sort()) {
    keep.push(...arr.sort((a,b) => rank(b) - rank(a)).slice(0, perMonthCap));
  }
  return keep;
}
function scenarioRows(all, scenario) {
  const base = all.filter((r) => scenario.lanes.includes(r.lane_key));
  if (!scenario.mirrorMonthlyCap) return base;
  const nonMirror = base.filter((r) => r.lane_key !== 'CORE_P1_MIRROR_WTA_OTHER');
  const mirror = capMirror(base.filter((r) => r.lane_key === 'CORE_P1_MIRROR_WTA_OTHER'), scenario.mirrorMonthlyCap);
  return [...nonMirror, ...mirror].sort((a,b) => `${a.event_date} ${a.event_time} ${a.signal_key}`.localeCompare(`${b.event_date} ${b.event_time} ${b.signal_key}`));
}
function summarize(rows) {
  const units = rows.reduce((s,r) => s + Number(r.grouped_profit_units || 0), 0);
  return {
    rows: rows.length,
    wins: rows.filter((r) => r.result === 'WIN').length,
    losses: rows.filter((r) => r.result === 'LOSS').length,
    profit_units: Number(units.toFixed(6)),
    staked_units: rows.length,
    roi_pct: rows.length ? Number(((units / rows.length) * 100).toFixed(2)) : 0,
    worst_row_units: rows.length ? Number(Math.min(...rows.map((r) => Number(r.grouped_profit_units || 0))).toFixed(6)) : 0,
    best_row_units: rows.length ? Number(Math.max(...rows.map((r) => Number(r.grouped_profit_units || 0))).toFixed(6)) : 0,
    first_date: rows[0]?.event_date || '',
    last_date: rows[rows.length - 1]?.event_date || '',
  };
}
function groupSummary(rows, field) {
  const m = new Map();
  for (const r of rows) { const k = r[field] || 'UNKNOWN'; if (!m.has(k)) m.set(k, []); m.get(k).push(r); }
  return [...m.entries()].sort(([a],[b]) => a.localeCompare(b)).map(([key, xs]) => ({ [field]: key, ...summarize(xs) }));
}
function compound(rows, risk) {
  let bank = bankroll; let peak = bankroll; let maxDd = 0; let streak = 0; let worstStreak = 0;
  const ledger = [];
  rows.forEach((r, i) => {
    const before = bank;
    const unit = Number(r.grouped_profit_units || 0);
    const pnl = before * risk * unit;
    bank += pnl;
    peak = Math.max(peak, bank);
    const dd = peak ? (peak - bank) / peak : 0;
    maxDd = Math.max(maxDd, dd);
    if (unit < 0) streak += 1; else streak = 0;
    worstStreak = Math.max(worstStreak, streak);
    ledger.push({ ...r, index: i + 1, risk_pct: risk, balance_before: Number(before.toFixed(2)), pnl_cash: Number(pnl.toFixed(2)), balance_after: Number(bank.toFixed(2)), drawdown_pct: Number((dd * 100).toFixed(2)) });
  });
  return { risk_pct: risk, final_bankroll: Number(bank.toFixed(2)), net_profit: Number((bank-bankroll).toFixed(2)), return_pct: Number(((bank/bankroll-1)*100).toFixed(2)), max_drawdown_pct: Number((maxDd*100).toFixed(2)), worst_losing_streak: worstStreak, ledger };
}

const scenarios = [
  { scenario: 'S1_CORE_REVERSE', label: 'Core + Reverse only', lanes: ['CORE_P1_ATP_GS_BET365','CORE_P2_GS_REVERSE_STRETCH_BET365'] },
  { scenario: 'S2_CORE_REVERSE_RESEARCH_P2', label: 'Core + Reverse + Research P2', lanes: ['CORE_P1_ATP_GS_BET365','CORE_P2_GS_REVERSE_STRETCH_BET365','RESEARCH_P2_GS_26_46_BET365'] },
  { scenario: 'S3_CORE_REVERSE_RESEARCH_P2_V3', label: 'Core + Reverse + Research P2 + V3', lanes: ['CORE_P1_ATP_GS_BET365','CORE_P2_GS_REVERSE_STRETCH_BET365','RESEARCH_P2_GS_26_46_BET365','VIP_P2_V3_SHAPE'] },
  { scenario: 'S4_CORE_REVERSE_MIRROR_TOP5_MONTH', label: 'Core + Reverse + top 5 Mirror/month', lanes: ['CORE_P1_ATP_GS_BET365','CORE_P2_GS_REVERSE_STRETCH_BET365','CORE_P1_MIRROR_WTA_OTHER'], mirrorMonthlyCap: 5 },
  { scenario: 'S5_CORE_REVERSE_RESEARCH_P2_V3_MIRROR_TOP5_MONTH', label: 'Core + Reverse + Research P2 + V3 + top 5 Mirror/month', lanes: ['CORE_P1_ATP_GS_BET365','CORE_P2_GS_REVERSE_STRETCH_BET365','RESEARCH_P2_GS_26_46_BET365','VIP_P2_V3_SHAPE','CORE_P1_MIRROR_WTA_OTHER'], mirrorMonthlyCap: 5 },
  { scenario: 'S6_ALL_PROFIT_CANDIDATES_NO_MIRROR', label: 'Core + Reverse + Research P2 + V3 only', lanes: ['CORE_P1_ATP_GS_BET365','CORE_P2_GS_REVERSE_STRETCH_BET365','RESEARCH_P2_GS_26_46_BET365','VIP_P2_V3_SHAPE'] },
  { scenario: 'NEGATIVE_CORE_CLUSTER_PLUS_ONLY', label: 'Core Cluster Plus only negative control', lanes: ['VIP_P1_ATP_GS_MULTI'] },
  { scenario: 'MIRROR_ONLY', label: 'Mirror only diagnostic', lanes: ['CORE_P1_MIRROR_WTA_OTHER'] },
];

function main() {
  if (!fs.existsSync(inputPath)) { console.error(`Missing input ${inputPath}. Run live-scanner-parity backtest first.`); process.exit(2); }
  ensureDir(outDir);
  const rows = parseCsv(fs.readFileSync(inputPath, 'utf8')).sort((a,b) => `${a.event_date} ${a.event_time} ${a.signal_key}`.localeCompare(`${b.event_date} ${b.event_time} ${b.signal_key}`));
  const allScenarioRows = [];
  const summaryRows = [];
  const monthlyRows = [];
  const byLaneRows = [];
  const compRows = [];
  const drawdownRows = [];
  for (const s of scenarios) {
    const selected = scenarioRows(rows, s).map((r) => ({ scenario: s.scenario, scenario_label: s.label, ...r }));
    allScenarioRows.push(...selected);
    summaryRows.push({ scenario: s.scenario, scenario_label: s.label, ...summarize(selected) });
    monthlyRows.push(...groupSummary(selected, 'month').map((r) => ({ scenario: s.scenario, ...r })));
    byLaneRows.push(...groupSummary(selected, 'lane_key').map((r) => ({ scenario: s.scenario, ...r })));
    for (const risk of riskPcts) {
      const c = compound(selected, risk);
      compRows.push({ scenario: s.scenario, risk_pct: risk, final_bankroll: c.final_bankroll, net_profit: c.net_profit, return_pct: c.return_pct, max_drawdown_pct: c.max_drawdown_pct, worst_losing_streak: c.worst_losing_streak });
      drawdownRows.push(...c.ledger.map((r) => ({ scenario: s.scenario, risk_pct: risk, index: r.index, event_date: r.event_date, lane_key: r.lane_key, match_name: r.match_name, unit_result: r.grouped_profit_units, balance_before: r.balance_before, pnl_cash: r.pnl_cash, balance_after: r.balance_after, drawdown_pct: r.drawdown_pct })));
    }
  }

  const fields = ['scenario','scenario_label','event_date','event_time','match_name','tournament_name','bookmaker','telegram_room','lane_key','lane_class','access','public_signal_name','target_scores','first_set_score','result','protected_grouped_odds','grouped_profit_units','skew','public_tier','signal_key'];
  writeCsv(path.join(outDir, 'optimized_profitable_lanes_rows.csv'), allScenarioRows, fields);
  writeCsv(path.join(outDir, 'optimized_profitable_lanes_summary.csv'), summaryRows, ['scenario','scenario_label','rows','wins','losses','profit_units','staked_units','roi_pct','worst_row_units','best_row_units','first_date','last_date']);
  writeCsv(path.join(outDir, 'optimized_profitable_lanes_monthly.csv'), monthlyRows, ['scenario','month','rows','wins','losses','profit_units','staked_units','roi_pct','worst_row_units','best_row_units','first_date','last_date']);
  writeCsv(path.join(outDir, 'optimized_profitable_lanes_by_lane.csv'), byLaneRows, ['scenario','lane_key','rows','wins','losses','profit_units','staked_units','roi_pct','worst_row_units','best_row_units','first_date','last_date']);
  writeCsv(path.join(outDir, 'optimized_profitable_lanes_compounding.csv'), compRows, ['scenario','risk_pct','final_bankroll','net_profit','return_pct','max_drawdown_pct','worst_losing_streak']);
  writeCsv(path.join(outDir, 'optimized_profitable_lanes_drawdown.csv'), drawdownRows, ['scenario','risk_pct','index','event_date','lane_key','match_name','unit_result','balance_before','pnl_cash','balance_after','drawdown_pct']);
  const summary = { generated_at: new Date().toISOString(), input_file: inputPath, source_rows: rows.length, scenarios: summaryRows, compounding: compRows, note: 'Optimized parity scenarios from live scanner customer rows. Core Cluster Plus remains negative control. Mirror is tested full and limited because historical full Mirror added volume but little edge.' };
  writeJson(path.join(outDir, 'optimized_profitable_lanes_summary.json'), summary);
  fs.writeFileSync(path.join(outDir, 'optimized_profitable_lanes_report.md'), ['# Optimized Profitable Lane Parity Test', '', `Generated: ${summary.generated_at}`, `Input rows: ${rows.length}`, '', '## Flat Results', ...summaryRows.map((s) => `- ${s.scenario}: ${s.rows} rows, ${s.profit_units}u, ROI ${s.roi_pct}%, worst ${s.worst_row_units}u`), '', '## Compounding', ...compRows.map((c) => `- ${c.scenario} @ ${(c.risk_pct*100).toFixed(1)}%: final $${c.final_bankroll}, max DD ${c.max_drawdown_pct}%`), '', '## Notes', '- S2 and S3 are the key candidates for main aggressive/live-forward tracking.', '- Mirror top-5/month tests whether limited volume helps without full Mirror dilution.', '- Core Cluster Plus is kept as negative control and should not be promoted without new evidence.'].join('\n') + '\n', 'utf8');
  console.log(JSON.stringify(summary, null, 2));
}
main();
